// ── Theory Screen ─────────────────────────────────────────────────
function TheoryScreen({ topic, onStartQuiz, onBack }) {
  const theory = THEORY[topic.id];
  if (!theory) return null;
  const [open, setOpen] = React.useState(null); // index of open section

  return (
    <div className="quiz">
      {/* Top bar */}
      <div className="quiz-bar">
        <button className="icon-btn" onClick={onBack} aria-label="Назад">
          <UIcon name="back" size={18} />
        </button>
        <div className="quiz-topic">
          <TopicIcon id={topic.id} size={18} />
          <span>{topic.name} — Теория</span>
        </div>
        <div style={{ width: 36 }} />
      </div>

      {/* Card */}
      <div className="theory-card reveal">
        <div className="theory-header">
          <span className="theory-icon"><TopicIcon id={topic.id} size={36} /></span>
          <div>
            <div className="theory-title">{theory.title}</div>
            <div className="theory-count">{theory.sections.length} раздела</div>
          </div>
        </div>

        <div className="theory-sections">
          {theory.sections.map((sec, i) => (
            <div className="theory-section" key={i}>
              <button className={`theory-sec-head ${open === i ? 'open' : ''}`}
                      onClick={() => setOpen(open === i ? null : i)}>
                <span>{sec.heading}</span>
                <span className="theory-chevron">{open === i ? '▲' : '▼'}</span>
              </button>

              {open === i && (
                <div className="theory-sec-body reveal">
                  {sec.body && (
                    <p className="theory-text">
                      {sec.body.split('\n').map((line, j) => (
                        <React.Fragment key={j}>{line}{j < sec.body.split('\n').length - 1 && <br/>}</React.Fragment>
                      ))}
                    </p>
                  )}
                  {sec.formula && (
                    <div className="theory-formula">
                      {window.katex
                        ? <window.MathBlock expr={sec.formula} />
                        : <code>{sec.formula}</code>}
                    </div>
                  )}
                  {sec.graph && window.Graph && (
                    <Graph
                      fns={sec.graph.fns || [sec.graph.fn]}
                      labels={sec.graph.labels || []}
                      xMin={sec.graph.xMin ?? -6}
                      xMax={sec.graph.xMax ?? 6}
                      yMin={sec.graph.yMin ?? -4}
                      yMax={sec.graph.yMax ?? 4}
                    />
                  )}
                  {sec.table && (
                    <div className="theory-table-wrap">
                      <table className="theory-table">
                        <tbody>
                          {sec.table.map((row, ri) => (
                            <tr key={ri}>
                              {row.map((cell, ci) => (
                                ri === 0
                                  ? <th key={ci}>{cell}</th>
                                  : <td key={ci}>{cell}</td>
                              ))}
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  )}
                  {sec.examples && sec.examples.length > 0 && (
                    <div className="theory-examples">
                      <div className="theory-ex-label">Примеры:</div>
                      {sec.examples.map((ex, j) => (
                        <div className="theory-ex" key={j}>
                          {window.KatexInline && /[\^_\\{}\[\]]/.test(ex)
                            ? <KatexInline expr={ex} />
                            : ex}
                        </div>
                      ))}
                    </div>
                  )}
                </div>
              )}
            </div>
          ))}
        </div>

        <div className="theory-footer">
          <button className="btn-ghost" onClick={onBack}>
            <UIcon name="back" size={16} /><span>К маршрутам</span>
          </button>
          <button className="btn-solid" onClick={onStartQuiz}>
            <UIcon name="arrow" size={16} stroke={2} /><span>Начать тест</span>
          </button>
        </div>
      </div>
    </div>
  );
}

Object.assign(window, { THEORY, TheoryScreen });

